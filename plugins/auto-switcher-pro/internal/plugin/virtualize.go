// Host callback method names exposed by CLIProxyAPI for auth-file management.
const (
	hostMethodAuthList   = "host.auth.list"
	hostMethodAuthGet    = "host.auth.get"
	hostMethodAuthSave   = "host.auth.save"
	hostMethodAuthDelete = "host.auth.delete"
)

// virtualizeRoutePath is the primary plugin-relative management route. The host resolves
// it under /v0/management/, i.e. POST /v0/management/auto-switcher-pro/virtualize.
const (
	virtualizeRoutePath = "/auto-switcher-pro/virtualize"
)

var (
	authFileSuffixPattern = regexp.MustCompile(`(?i)\.json$`)
	safePrefixPattern     = regexp.MustCompile(`^[a-zA-Z0-9_-]+$`)
	safeNamePattern       = regexp.MustCompile(`^[A-Za-z0-9._@+-]+\.json$`)
)

// VirtualizeRequest asks the plugin to clone a physical auth file into a new
// virtual credential file for a different model family (prefix + exclusions).
type VirtualizeRequest struct {
	SourceFileName string   `json:"source_file_name"`
	Name           string   `json:"name"`
	Prefix         string   `json:"prefix"`
	TargetModels   []string `json:"target_models"`
	TargetPatterns []string `json:"target_patterns"`
	OppositeModels []string `json:"opposite_models"`
	ExcludedModels []string `json:"excluded_models"`
}

// VirtualizeResult reports the newly written virtual credential file.
type VirtualizeResult struct {
	Name   string `json:"name"`
	Path   string `json:"path"`
	Prefix string `json:"prefix"`
}

type hostAuthFileEntry struct {
	Name      string `json:"name"`
	AuthIndex string `json:"auth_index"`
	Path      string `json:"path"`
}

type hostAuthListResult struct {
	Files []hostAuthFileEntry `json:"files"`
}

type hostAuthGetResult struct {
	JSON json.RawMessage `json:"json"`
}

type hostAuthSaveResult struct {
	Name string `json:"name"`
	Path string `json:"path"`
}

// Virtualize reads the physical credential identified by SourceFileName through
// the host, clones its JSON with the requested prefix and (optional) exclusion
// list, and persists the clone as a new auth file. Tokens never reach the caller.
func Virtualize(req VirtualizeRequest) (VirtualizeResult, error) {
	if hostCaller == nil {
		return VirtualizeResult{}, fmt.Errorf("host bridge is not available")
	}

	source := strings.TrimSpace(req.SourceFileName)
	if source == "" {
		return VirtualizeResult{}, fmt.Errorf("source_file_name is required")
	}
	if !isValidAuthFileName(source) {
		return VirtualizeResult{}, fmt.Errorf("invalid source_file_name")
	}

	prefix := strings.TrimSpace(req.Prefix)
	if prefix == "" {
		return VirtualizeResult{}, fmt.Errorf("prefix is required")
	}
	if !safePrefixPattern.MatchString(prefix) {
		return VirtualizeResult{}, fmt.Errorf("invalid prefix")
	}

	targetName := strings.TrimSpace(req.Name)
	if targetName == "" {
		targetName = deriveVirtualName(source, prefix)
	}
	if !isValidAuthFileName(targetName) {
		return VirtualizeResult{}, fmt.Errorf("invalid name")
	}

	authIndex, errResolve := resolveAuthIndex(source)
	if errResolve != nil {
		return VirtualizeResult{}, errResolve
	}

	metadata, errJSON := readAuthMetadata(authIndex)
	if errJSON != nil {
		return VirtualizeResult{}, errJSON
	}

	// Overwrite the routing prefix and compute the model exclusion list. When an
	// explicit list is supplied it wins; otherwise the target-family models are
	// released from the inherited exclusions and the opposite-family models are
	// added, preserving account-specific limits of the source credential.
	metadata["prefix"] = prefix
	switch {
	case req.ExcludedModels != nil:
		metadata["excluded_models"] = req.ExcludedModels
	case len(req.TargetModels) > 0 || len(req.OppositeModels) > 0 || len(req.TargetPatterns) > 0:
		metadata["excluded_models"] = computeVirtualExclusions(metadata["excluded_models"], req.TargetModels, req.OppositeModels, req.TargetPatterns)
	}

	saved, errSave := saveAuthMetadata(targetName, metadata)
	if errSave != nil {
		return VirtualizeResult{}, errSave
	}

	return VirtualizeResult{
		Name:   saved.Name,
		Path:   saved.Path,
		Prefix: prefix,
	}, nil
}

func deriveVirtualName(sourceFileName, prefix string) string {
	base := authFileSuffixPattern.ReplaceAllString(sourceFileName, "")
	return fmt.Sprintf("%s.%s.json", base, prefix)
}

// isValidAuthFileName accepts the identifiers generated by CLIProxyAPI (which may
// contain '@' for account emails) while rejecting traversal and separators.
func isValidAuthFileName(name string) bool {
	if !safeNamePattern.MatchString(name) {
		return false
	}
	return !strings.Contains(name, "..")
}

// computeVirtualExclusions removes the models the clone should serve (target)
// from the inherited exclusion list and adds the models it must not serve
// (opposite), preserving account-specific exclusions of the source credential.
func computeVirtualExclusions(raw any, targetModels, oppositeModels, targetPatterns []string) []string {
	target := make(map[string]struct{}, len(targetModels))
	for _, m := range targetModels {
		if key := strings.TrimSpace(m); key != "" {
			target[key] = struct{}{}
		}
	}
	patterns := make([]string, 0, len(targetPatterns))
	for _, p := range targetPatterns {
		if trimmed := strings.ToLower(strings.TrimSpace(p)); trimmed != "" {
			patterns = append(patterns, trimmed)
		}
	}
	matchesTarget := func(model string) bool {
		if _, ok := target[model]; ok {
			return true
		}
		lower := strings.ToLower(model)
		for _, p := range patterns {
			if strings.Contains(lower, p) {
				return true
			}
		}
		return false
	}

	seen := make(map[string]struct{})
	out := make([]string, 0, len(oppositeModels))
	for _, m := range toStringSlice(raw) {
		if matchesTarget(m) {
			continue
		}
		if _, dup := seen[m]; dup {
			continue
		}
		seen[m] = struct{}{}
		out = append(out, m)
	}
	for _, m := range oppositeModels {
		m = strings.TrimSpace(m)
		if m == "" {
			continue
		}
		if _, dup := seen[m]; dup {
			continue
		}
		seen[m] = struct{}{}
		out = append(out, m)
	}
	return out
}

func toStringSlice(raw any) []string {
	switch v := raw.(type) {
	case []string:
		return v
	case []any:
		out := make([]string, 0, len(v))
		for _, item := range v {
			if s, ok := item.(string); ok {
				if trimmed := strings.TrimSpace(s); trimmed != "" {
					out = append(out, trimmed)
				}
			}
		}
		return out
	default:
		return nil
	}
}

func resolveAuthIndex(sourceFileName string) (string, error) {
	raw, err := hostCaller(hostMethodAuthList, map[string]any{})
	if err != nil {
		return "", fmt.Errorf("host.auth.list failed: %w", err)
	}
	var listed hostAuthListResult
	if err := json.Unmarshal(raw, &listed); err != nil {
		return "", fmt.Errorf("decode host.auth.list result: %w", err)
	}
	for _, file := range listed.Files {
		if strings.EqualFold(strings.TrimSpace(file.Name), sourceFileName) {
			if strings.TrimSpace(file.AuthIndex) == "" {
				return "", fmt.Errorf("auth_index unavailable for %s", sourceFileName)
			}
			return file.AuthIndex, nil
		}
	}
	return "", fmt.Errorf("source auth file not found: %s", sourceFileName)
}

func readAuthMetadata(authIndex string) (map[string]any, error) {
	raw, err := hostCaller(hostMethodAuthGet, map[string]any{"auth_index": authIndex})
	if err != nil {
		return nil, fmt.Errorf("host.auth.get failed: %w", err)
	}
	var got hostAuthGetResult
	if err := json.Unmarshal(raw, &got); err != nil {
		return nil, fmt.Errorf("decode host.auth.get result: %w", err)
	}
	if len(got.JSON) == 0 {
		return nil, fmt.Errorf("host.auth.get returned empty credential JSON")
	}
	var metadata map[string]any
	if err := json.Unmarshal(got.JSON, &metadata); err != nil {
		return nil, fmt.Errorf("decode credential JSON: %w", err)
	}
	return metadata, nil
}

func saveAuthMetadata(name string, metadata map[string]any) (hostAuthSaveResult, error) {
	raw, err := hostCaller(hostMethodAuthSave, map[string]any{"name": name, "json": metadata})
	if err != nil {
		return hostAuthSaveResult{}, fmt.Errorf("host.auth.save failed: %w", err)
	}
	var saved hostAuthSaveResult
	if err := json.Unmarshal(raw, &saved); err != nil {
		return hostAuthSaveResult{}, fmt.Errorf("decode host.auth.save result: %w", err)
	}
	if strings.TrimSpace(saved.Name) == "" {
		saved.Name = name
	}
	return saved, nil
}

func isVirtualizePath(rawPath string) bool {
	normalized := strings.TrimSpace(rawPath)
	if idx := strings.IndexAny(normalized, "?#"); idx != -1 {
		normalized = normalized[:idx]
	}
	normalized = strings.TrimRight(normalized, "/")
	return strings.HasSuffix(normalized, virtualizeRoutePath)
}

// VirtualizeResponse is the JSON payload returned by the virtualize route. It is
// always delivered with HTTP 200 so the client can surface the plugin's message.
type VirtualizeResponse struct {
	OK      bool   `json:"ok"`
	Name    string `json:"name,omitempty"`
	Path    string `json:"path,omitempty"`
	Prefix  string `json:"prefix,omitempty"`
	Error   string `json:"error,omitempty"`
	Message string `json:"message,omitempty"`
}

// handleVirtualizeHTTP serves POST /v0/management/auto-switcher-pro/virtualize.
func handleVirtualizeHTTP(req ManagementRequestPayload) ([]byte, error) {
	var payload VirtualizeRequest
	if len(req.Body) > 0 {
		if err := json.Unmarshal(req.Body, &payload); err != nil {
			return jsonManagementResponse(http.StatusBadRequest, map[string]string{
				"error":   "bad_request",
				"message": "malformed virtualize JSON request payload",
			})
		}
	}

	result, err := Virtualize(payload)
	if err != nil {
		return jsonManagementResponse(http.StatusOK, VirtualizeResponse{
			OK:      false,
			Error:   "virtualize_failed",
			Message: err.Error(),
		})
	}
	return jsonManagementResponse(http.StatusOK, VirtualizeResponse{
		OK:     true,
		Name:   result.Name,
		Path:   result.Path,
		Prefix: result.Prefix,
	})
}

// DeleteVirtual deletes a virtual auth file from CPAMC disk via host bridge.
func DeleteVirtual(name string) error {
	if hostCaller == nil {
		return fmt.Errorf("host bridge is not available")
	}

	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return fmt.Errorf("auth file name is required")
	}
	if !isValidAuthFileName(trimmed) {
		return fmt.Errorf("invalid auth file name: %s", trimmed)
	}

	_, err := hostCaller(hostMethodAuthDelete, map[string]any{"name": trimmed})
	if err != nil {
		return fmt.Errorf("host.auth.delete failed for %s: %w", trimmed, err)
	}
	return nil
}

// handleDeleteVirtualHTTP serves DELETE /v0/management/auto-switcher-pro/virtualize?name=...
func handleDeleteVirtualHTTP(req ManagementRequestPayload) ([]byte, error) {
	name := ""
	if u, err := url.Parse(req.Path); err == nil {
		name = strings.TrimSpace(u.Query().Get("name"))
	}
	if name == "" && len(req.Body) > 0 {
		var body struct {
			Name string `json:"name"`
		}
		if err := json.Unmarshal(req.Body, &body); err == nil {
			name = strings.TrimSpace(body.Name)
		}
	}

	if name == "" {
		return jsonManagementResponse(http.StatusBadRequest, map[string]string{
			"error":   "bad_request",
			"message": "auth file name is required",
		})
	}

	err := DeleteVirtual(name)
	if err != nil {
		return jsonManagementResponse(http.StatusOK, map[string]any{
			"ok":      false,
			"error":   "delete_failed",
			"message": err.Error(),
		})
	}
	return jsonManagementResponse(http.StatusOK, map[string]any{
		"ok":   true,
		"name": name,
	})
}

// ComputeSpecialistExclusions returns a sorted, deduplicated slice containing
// every model from allModels except targetModel.
func ComputeSpecialistExclusions(allModels []string, targetModel string) []string {
	target := strings.TrimSpace(targetModel)
	seen := make(map[string]struct{})
	out := make([]string, 0, len(allModels))
	for _, m := range allModels {
		clean := strings.TrimSpace(m)
		if clean == "" || clean == target {
			continue
		}
		if _, exists := seen[clean]; !exists {
			seen[clean] = struct{}{}
			out = append(out, clean)
		}
	}
	sort.Strings(out)
	return out
}

func jsonManagementResponse(statusCode int, body any) ([]byte, error) {
	raw, errMarshal := json.Marshal(body)
	if errMarshal != nil {
		return nil, errMarshal
	}
	resp := ManagementResponsePayload{
		StatusCode: statusCode,
		Headers: map[string][]string{
			"Content-Type":           {"application/json; charset=utf-8"},
			"X-Content-Type-Options": {"nosniff"},
		},
		Body: base64.StdEncoding.EncodeToString(raw),
	}
	encoded, errEncode := json.Marshal(resp)
	if errEncode != nil {
		return nil, errEncode
	}
	return OKEnvelope(encoded), nil
}
